<?php

declare(strict_types=1);

namespace Vasoft\Joke\Contract\RateLimit;

/**
 * Контракт для хранилища счётчиков rate limiting'а.
 *
 * Реализация должна обеспечивать:
 * - Атомарность increment() в рамках одного процесса
 * - Поддержку TTL для автоматической очистки устаревших данных
 * - Надёжное хранение после сбоев (для файлового хранилища)
 */
interface StorageInterface
{
    /**
     * Инкрементирует счётчик для ключа и возвращает новое значение.
     *
     * Запись должна быть атомарной в рамках одного процесса.
     * Если ключ не существует, создаёт его с значением 1.
     * Всегда инкрементирует, даже если счётчик превышает лимит.
     *
     * @param string $key Идентификатор клиента (e.g. "ratelimit:192.168.1.1")
     * @param int $ttl Время жизни (секунды). По умолчанию 3600.
     * @return int Новое значение счётчика
     */
    public function increment(string $key, int $ttl = 3600): int;

    /**
     * Получает текущее значение счётчика.
     *
     * Возвращает 0, если ключ не существует или устарел.
     *
     * @param string $key Идентификатор клиента
     * @return int Текущее значение или 0
     */
    public function get(string $key): int;

    /**
     * Очищает все данные в хранилище.
     *
     * Используется в тестах. Должна быть безопасна при многократном вызове.
     */
    public function clear(): void;
}
